// Runs the Prisma CLI with the provider picked from DATABASE_URL:
//   postgres:// | postgresql://  → prisma/schema.pg.prisma (generated here: schema.prisma with provider "postgresql")
//   anything else (file:./dev.db) → prisma/schema.prisma (SQLite, local dev)
// schema.prisma stays the only schema you edit. Usage from apps/api:
//   node scripts/prisma.mjs generate
//   node scripts/prisma.mjs db push --skip-generate
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(apiDir, '.env');
if (existsSync(envFile)) process.loadEnvFile(envFile); // already-exported variables win (same as main.ts)

const isPostgres = /^postgres(ql)?:\/\//i.test(process.env.DATABASE_URL ?? '');
let schema = join(apiDir, 'prisma', 'schema.prisma');
if (isPostgres) {
  const src = readFileSync(schema, 'utf8');
  const pg = src.replace(/(datasource\s+db\s*\{[^}]*?provider\s*=\s*)"sqlite"/, '$1"postgresql"');
  if (pg === src) {
    process.stderr.write('[prisma] datasource provider "sqlite" not found in schema.prisma\n');
    process.exit(1);
  }
  schema = join(apiDir, 'prisma', 'schema.pg.prisma');
  writeFileSync(schema, `// GENERATED by scripts/prisma.mjs from schema.prisma. Do not edit, do not commit.\n${pg}`);
}

const cli = createRequire(import.meta.url).resolve('prisma/build/index.js');
const args = [...process.argv.slice(2), '--schema', schema];
process.stdout.write(`[prisma] provider=${isPostgres ? 'postgresql' : 'sqlite'}: prisma ${process.argv.slice(2).join(' ')}\n`);
const run = spawnSync(process.execPath, [cli, ...args], { stdio: 'inherit', cwd: apiDir });
process.exit(run.status ?? 1);
